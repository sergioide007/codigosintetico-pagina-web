#!/bin/sh
# Builds worker/dist/worker-dashboard.js: templates.js + index.js in ONE file, for pasting into
# Cloudflare Dashboard → Workers & Pages → specsolid-newsletter → Edit code (no imports allowed there).
# `npx wrangler deploy` does not need this file: it bundles worker/src/index.js itself.
cd "$(dirname "$0")" || exit 1
{
  echo "// GENERATED by worker/build-dashboard.sh from src/templates.js + src/index.js. Do not edit by hand."
  grep -v '^export {' src/templates.js
  grep -v '^import .* from "./templates.js";' src/index.js
} > dist/worker-dashboard.js
echo "built worker/dist/worker-dashboard.js ($(wc -l < dist/worker-dashboard.js) lines)"
